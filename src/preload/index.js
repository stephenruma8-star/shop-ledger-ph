  setAppPreferences: (prefs) => ipcRenderer.invoke('set-app-preferences', prefs),
  getAppVersion: () => ipcRenderer.invoke('get-app-version'),
  getLogsInfo: () => ipcRenderer.invoke('logs-info'),
  openLogsFolder: () => ipcRenderer.invoke('open-logs-folder'),
  logRenderer: (level, message) => ipcRenderer.send('log-renderer', { level, message }),
  onHiddenToTray: (callback) => ipcRenderer.on('hidden-to-tray', () => callback()),
  saveLogo: (dataUrl) => ipcRenderer.invoke('save-logo', { dataUrl }),
  getLogo: () => ipcRenderer.invoke('get-logo'),
  onShortcut: (callback) => ipcRenderer.on('shortcut', (_, action) => callback(action)),
  onUpdateAvailable: (callback) => ipcRenderer.on('update-available', (_, info) => callback(info)),
  onUpdateNotAvailable: (callback) => ipcRenderer.on('update-not-available', () => callback()),
  onUpdateError: (callback) => ipcRenderer.on('update-error', (_, message) => callback(message)),
  onUpdateDownloaded: (callback) => ipcRenderer.on('update-downloaded', (_, info) => callback(info)),
  onUpdateProgress: (callback) => ipcRenderer.on('update-progress', (_, info) => callback(info)),
  checkUpdate: () => ipcRenderer.invoke('check-update'),
  downloadUpdate: () => ipcRenderer.invoke('download-update'),
  installUpdate: () => ipcRenderer.invoke('install-update'),
  signalLanUpdate: () => ipcRenderer.invoke('signal-lan-update'),
  onLanUpdateSignal: (callback) => ipcRenderer.on('lan-update-signal', (_, info) => callback(info)),
  selectFolder: () => ipcRenderer.invoke('select-folder'),
  saveEncryptedBackupToPath: (data, password, filename, folder) => ipcRenderer.invoke('save-encrypted-backup-to-path', { data, password, filename, folder }),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  rebuildApp: () => ipcRenderer.invoke('rebuild-app'),
